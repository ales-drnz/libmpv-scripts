"""
Embeds a CA-certificate root bundle into FFmpeg's OpenSSL TLS backend so HTTPS
peer verification works with NO on-device cert file. This is required on hosts
whose OpenSSL default cert path (the build-time --openssldir) does not exist at
runtime: sandboxed macOS, iOS and Android in particular.

The CA bundle and the hand-written loader/header live in the embed_cacert/
sibling directory (cacert.pem, ca_bundle.h, ca_bundle_loader.c) — edit them
THERE, like the mpv-side pcm_tap/ and bulk_analysis/ patches.

Modifies (all under libavformat/):
  - ca_bundle.h         (copied in: extern array decls + ff_load_embedded_ca proto)
  - ca_bundle_loader.c  (copied in: the X509_STORE loader)
  - ca_bundle_data.c    (GENERATED here from cacert.pem: the PEM byte array)
  - Makefile            (OBJS-$(CONFIG_OPENSSL) += ca_bundle_data.o ca_bundle_loader.o)
  - tls_openssl.c       (#include "ca_bundle.h"; load the embedded roots when
                         tls_verify is on and no explicit ca_file is set,
                         treating an empty ca_file as unset so a blank
                         tls-ca-file falls back to the bundle)

With tls_verify off, mpv's default, nothing reads the roots, and parsing the
bundle and the system store cost every handshake milliseconds of CPU. Both
load only when the peer is verified (VERIFY_MARKER).

Idempotency: the text edits (Makefile, tls_openssl.c) are MARKER-guarded; the
.c/.h are (re)written every run so a refreshed cacert.pem propagates on rebuild.
A tree patched by the version without the verify gate is brought up to date.
Anchors that go missing fail the patch — an ffmpeg layout change must fail
loudly, not silently drop HTTPS trust — and no file is written until every
anchor has matched.

Usage:
    python3 patch_ffmpeg_embed_cacert.py <ffmpeg_source_dir>
"""
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / '_lib'))
import anchor  # noqa: E402

MARKER = 'MAK_EMBED_CACERT_V1'
VERIFY_MARKER = 'MAK_EMBED_CACERT_VERIFY'

MAKEFILE = 'libavformat/Makefile'
TLS = 'libavformat/tls_openssl.c'


def generate_data_c(pem):
    rows = []
    for i in range(0, len(pem), 12):
        chunk = pem[i:i + 12]
        rows.append('    ' + ''.join('0x%02x, ' % b for b in chunk).rstrip())
    return (
        '/* %s — generated by patch_ffmpeg_embed_cacert.py from cacert.pem.\n'
        ' * Do not edit; refresh the bundle via update_cacert.sh and rebuild. */\n'
        'const unsigned char ff_ca_bundle_pem[] = {\n'
        '%s\n'
        '};\n'
        'const unsigned int ff_ca_bundle_pem_len = %du;\n'
    ) % (MARKER, '\n'.join(rows), len(pem))


def patch_makefile(p):
    if 'ca_bundle_data.o' in p.text(MAKEFILE):
        print('Already patched: %s' % MAKEFILE)
        return
    p.regex(MAKEFILE,
            r'(TLS-OBJS-\$\(CONFIG_OPENSSL\)\s+\+= tls_openssl\.o)',
            r'\1\n'
            r'# ' + MARKER + '\n'
            r'OBJS-$(CONFIG_OPENSSL)                   += ca_bundle_data.o ca_bundle_loader.o',
            'tls_openssl.o OBJS line')


OLD = (
    '    if (s->ca_file) {\n'
    '        if (!SSL_CTX_load_verify_locations(c->ctx, s->ca_file, NULL))\n'
    '            av_log(h, AV_LOG_ERROR, "SSL_CTX_load_verify_locations %s\\n", openssl_get_error(c));\n'
    '    } else {\n'
    '        if (!SSL_CTX_set_default_verify_paths(c->ctx)) {\n'
    '            // Only log the failure but do not error out, as this is not fatal\n'
    '            av_log(h, AV_LOG_WARNING, "Failure setting default verify locations: %s\\n",\n'
    '                openssl_get_error(c));\n'
    '        }\n'
    '    }'
)
# The block as the version without the verify gate left it.
V1 = (
    '    /* ' + MARKER + ': an empty ca_file means "use the embedded roots",\n'
    '     * not "load a file named \'\'", so treat "" as unset. */\n'
    '    if (s->ca_file && s->ca_file[0]) {\n'
    '        if (!SSL_CTX_load_verify_locations(c->ctx, s->ca_file, NULL))\n'
    '            av_log(h, AV_LOG_ERROR, "SSL_CTX_load_verify_locations %s\\n", openssl_get_error(c));\n'
    '    } else {\n'
    '        if (ff_load_embedded_ca(c->ctx) < 0)\n'
    '            av_log(h, AV_LOG_WARNING, "Failed to load embedded CA bundle\\n");\n'
    '        /* Also honour any OS trust store the platform happens to expose. */\n'
    '        if (!SSL_CTX_set_default_verify_paths(c->ctx))\n'
    '            av_log(h, AV_LOG_VERBOSE, "No system verify locations: %s\\n",\n'
    '                openssl_get_error(c));\n'
    '    }'
)
NEW = (
    '    /* ' + MARKER + ': an empty ca_file means "use the embedded roots",\n'
    '     * not "load a file named \'\'", so treat "" as unset. */\n'
    '    if (s->ca_file && s->ca_file[0]) {\n'
    '        if (!SSL_CTX_load_verify_locations(c->ctx, s->ca_file, NULL))\n'
    '            av_log(h, AV_LOG_ERROR, "SSL_CTX_load_verify_locations %s\\n", openssl_get_error(c));\n'
    '    } else if (s->verify) {\n'
    '        /* ' + VERIFY_MARKER + ': the roots decide something only when\n'
    '         * the peer is verified. With tls_verify off, parsing them cost\n'
    '         * every handshake milliseconds of CPU for nothing. */\n'
    '        if (ff_load_embedded_ca(c->ctx) < 0)\n'
    '            av_log(h, AV_LOG_WARNING, "Failed to load embedded CA bundle\\n");\n'
    '        /* Also honour any OS trust store the platform happens to expose. */\n'
    '        if (!SSL_CTX_set_default_verify_paths(c->ctx))\n'
    '            av_log(h, AV_LOG_VERBOSE, "No system verify locations: %s\\n",\n'
    '                openssl_get_error(c));\n'
    '    }'
)


def patch_tls_openssl(p):
    if p.marked(TLS, VERIFY_MARKER):
        print('Already patched: %s' % TLS)
        return
    include = '#include "ca_bundle.h" /* ' + MARKER + ' */'
    if include not in p.text(TLS):
        inc_anchor = '#include <openssl/x509v3.h>'
        p.edit(TLS, inc_anchor, inc_anchor + '\n' + include, 'openssl include')
    p.optional(TLS, [(V1, NEW), (OLD, NEW)], 'CA-file verify block')


def apply(p):
    # The .c/.h are rewritten each run, so a refreshed cacert.pem propagates.
    for name in ('ca_bundle.h', 'ca_bundle_loader.c'):
        p.new_file('libavformat/' + name, p.asset('embed_cacert/' + name),
                   force=True)
    pem = (p.here / 'embed_cacert' / 'cacert.pem').read_bytes()
    p.new_file('libavformat/ca_bundle_data.c', generate_data_c(pem), force=True)
    patch_makefile(p)
    patch_tls_openssl(p)


anchor.main(apply, 'patch_ffmpeg_embed_cacert', marker=MARKER,
            usage='<ffmpeg_src_dir>')
