# =============================================================================
# build_libmpv_webos.sh
#
# Compiles mpv as libmpv.so for LG webOS TVs: armv7l, the 32-bit ARM EABI
# with softfp floats that flutter-webos builds apps for (webOS 26 on).
#
# === OUTPUT ===
# builds/release/libmpv_webos-armv7l.so
#
# === SYSTEM ===
# Run inside the mpv-build-webos image (`webos` stage of docker/Dockerfile),
# which has LG's webOS NDK in /opt/webos-ndk: GCC 13.3 and binutils for
# arm-webosmllib32-linux-gnueabi, and the TVs' sysroot (glibc 2.39, ALSA).
# Small wrappers named like a cross toolchain (arm-linux-gnueabi-gcc, ...)
# pass the NDK's compiler its sysroot and ABI, so every build system takes
# them as it takes gcc. The audio output is ao_alsa; PulseAudio and
# PipeWire are not in the sysroot. libstdc++ is the system's: the NDK has
# no static one.
#
# Usage (from project root):
#   ./scripts/build_libmpv_webos.sh
#
# Options (env vars):
#   WEBOS_NDK=dir           (default: /opt/webos-ndk)
#   JOBS=N                  (default: nproc)
#   FORCE_DOWNLOAD=1, KEEP_BUILD=1, WIPE_ALL=1, ENABLE_LTO_DEPS=0,
#   VIS_HIDDEN=0, SECTION_GC=0: as in build_libmpv_linux.sh
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

source "$SCRIPT_DIR/shared/_helpers.sh"
source "$SCRIPT_DIR/shared/_versions.sh"
source "$SCRIPT_DIR/shared/_audio_only.sh"
source "$SCRIPT_DIR/shared/_cross.sh"
source "$SCRIPT_DIR/build_openssl.sh"

# ── Parse args ────────────────────────────────────────────────────────────────
ARCH=armv7l
for arg in "$@"; do
  case "$arg" in
    --arch=armv7l) ;;
    --arch=*)   die "Unsupported ${arg} (webOS TVs run armv7l apps)" ;;
    --help|-h)  grep -E '^# ' "$0" | sed 's/^# //'; exit 0 ;;
    *) die "Unknown argument: $arg" ;;
  esac
done

# The wrappers' and autotools' triple, the NDK's, its ABI flags (those of
# its environment-setup script), and the names FFmpeg, meson and OpenSSL
# know the CPU by.
TRIPLE="arm-linux-gnueabi"
NDK_TRIPLE="arm-webosmllib32-linux-gnueabi"
WEBOS_NDK="${WEBOS_NDK:-/opt/webos-ndk}"
ABI_FLAGS="-mthumb -mfpu=neon -mfloat-abi=softfp -mcpu=cortex-a9 -mtune=cortex-a9"
MESON_CPU_FAMILY="arm"; MESON_CPU="armv7l"
OPENSSL_TARGET="linux-armv4"
OPENSSL_EXTRA=""
FFMPEG_ARCH_ARGS="--arch=arm --cpu=cortex-a9"

JOBS="${JOBS:-$(nproc 2>/dev/null || echo 4)}"
export PATH="$HOME/.local/bin:/usr/local/bin:$PATH"

export LIBPLACEBO_VERSION="7.349.0"

BUILD_DIR="${BUILD_DIR:-$LIBMPV_SCRIPTS_ROOT/builds/work/webOS/$ARCH}"
PREFIX="$BUILD_DIR/prefix"
SYSROOT="$WEBOS_NDK/sysroots/ca9v1-webosmllib32-linux-gnueabi"
NDK_BIN="$WEBOS_NDK/sysroots/x86_64-starfishsdk-linux/usr/bin/$NDK_TRIPLE"
TOOLS="$BUILD_DIR/bin"
mkdir -p "$BUILD_DIR" "$PREFIX/include" "$PREFIX/lib" "$TOOLS"

# ── Mirror all stdout + stderr to a timestamped log file ─────────────────────
LOG_DIR="$LIBMPV_SCRIPTS_ROOT/builds/logs"
mkdir -p "$LOG_DIR"
ls -t "$LOG_DIR"/build_webos-*_*.log 2>/dev/null | tail -n +21 | xargs rm -f 2>/dev/null || true
LOG_FILE="$LOG_DIR/build_webos-${ARCH}_$(date +%Y%m%d_%H%M%S).log"
exec > >(tee >(while IFS= read -r line; do
  printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$line"
done >> "$LOG_FILE")) 2>&1
echo "════════════════════════════════════════════════════════════"
echo "Build started: $(date)"
echo "Log file:      $LOG_FILE"
echo "FFmpeg:        $FFMPEG_VERSION   mpv: $MPV_VERSION   target: webos/$ARCH"
echo "Toolchain:     webOS NDK in $WEBOS_NDK"
echo "════════════════════════════════════════════════════════════"

# ── Sysroot ───────────────────────────────────────────────────────────────────
# The NDK's, as it is. Its .pc files say prefix=/usr: copies with the
# sysroot's path, so PKG_CONFIG_SYSROOT_DIR is not needed.
setup_sysroot() {
  [[ -f "$SYSROOT/usr/lib/libc.so.6" ]] || die "no webOS NDK sysroot at $SYSROOT (WEBOS_NDK)"
  local pcdir="$BUILD_DIR/sysroot-pkgconfig"
  rm -rf "$pcdir"; mkdir -p "$pcdir"
  local pc
  for pc in "$SYSROOT"/usr/lib/pkgconfig/*.pc "$SYSROOT"/usr/share/pkgconfig/*.pc; do
    [[ -f "$pc" ]] || continue
    sed -E "s#^(prefix|exec_prefix|libdir|includedir)[[:space:]]*=[[:space:]]*/usr#\1=$SYSROOT/usr#" "$pc" > "$pcdir/$(basename "$pc")"
  done
  SYSROOT_PKGCONFIG="$pcdir"
}

# ── Toolchain: the NDK's behind wrappers named like a cross toolchain ────────
setup_toolchain() {
  local tool
  for tool in gcc g++; do
    cat > "$TOOLS/$TRIPLE-$tool" <<EOF
#!/usr/bin/env bash
# Generated by build_libmpv_webos.sh: the webOS NDK's $tool.
exec "$NDK_BIN/$NDK_TRIPLE-$tool" --sysroot="$SYSROOT" $ABI_FLAGS "\$@"
EOF
    chmod +x "$TOOLS/$TRIPLE-$tool"
  done
  for tool in ar ranlib nm strip readelf objcopy; do
    ln -sf "$NDK_BIN/$NDK_TRIPLE-$tool" "$TOOLS/$TRIPLE-$tool"
  done
  export PATH="$TOOLS:$PATH"

  export CC="$TRIPLE-gcc" CXX="$TRIPLE-g++"
  export AR="$TRIPLE-ar" RANLIB="$TRIPLE-ranlib" NM="$TRIPLE-nm"
  export STRIP="$TRIPLE-strip" READELF="$TRIPLE-readelf" OBJCOPY="$TRIPLE-objcopy"

  export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig:$SYSROOT_PKGCONFIG"
  export PKG_CONFIG_PATH="$PKG_CONFIG_LIBDIR"
  export PKG_CONFIG="$TOOLS/$TRIPLE-pkg-config"
  cat > "$PKG_CONFIG" <<EOF
#!/usr/bin/env bash
# Generated by build_libmpv_webos.sh: the prefix's and the sysroot's .pc files only.
export PKG_CONFIG_LIBDIR="$PKG_CONFIG_LIBDIR"
export PKG_CONFIG_PATH="$PKG_CONFIG_LIBDIR"
exec pkg-config "\$@"
EOF
  chmod +x "$PKG_CONFIG"

  CROSS_MESON_FILE="$BUILD_DIR/cross-webos-$ARCH.meson"
  cat > "$CROSS_MESON_FILE" <<EOF
# Generated by build_libmpv_webos.sh.
[binaries]
c = '$CC'
cpp = '$CXX'
ar = '$AR'
ranlib = '$RANLIB'
strip = '$STRIP'
nm = '$NM'
pkgconfig = '$PKG_CONFIG'
cmake = 'cmake'

[host_machine]
system = 'linux'
cpu_family = '$MESON_CPU_FAMILY'
cpu = '$MESON_CPU'
endian = 'little'

[properties]
needs_exe_wrapper = true
EOF

  CROSS_CMAKE_FILE="$BUILD_DIR/cross-webos-$ARCH.cmake"
  cat > "$CROSS_CMAKE_FILE" <<EOF
# Generated by build_libmpv_webos.sh.
set(CMAKE_SYSTEM_NAME      Linux)
set(CMAKE_SYSTEM_PROCESSOR $MESON_CPU)
set(CMAKE_C_COMPILER       $CC)
set(CMAKE_CXX_COMPILER     $CXX)
set(CMAKE_AR     $TOOLS/$TRIPLE-ar CACHE FILEPATH "Archiver")
set(CMAKE_RANLIB $TOOLS/$TRIPLE-ranlib CACHE FILEPATH "Ranlib")
set(CMAKE_FIND_ROOT_PATH              $PREFIX $SYSROOT)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
EOF

  # What the cross_build_* of _cross.sh read: the configure host, the places
  # and the triple.
  export CROSS_AUTOTOOLS_HOST="--host=$TRIPLE"
  export CROSS_BUILD_DIR="$BUILD_DIR"
  export CROSS_PREFIX_DIR="$PREFIX"
  export CROSS_TRIPLE="$TRIPLE"
  FFMPEG_CROSS_ARGS="--enable-cross-compile --cross-prefix=$TRIPLE- --cc=$CC --cxx=$CXX --target-os=linux $FFMPEG_ARCH_ARGS --pkg-config=$PKG_CONFIG"

  LTO_EXTRA="$(lto_deps_cflags)"
  VIS_EXTRA="$(vis_deps_cflags)"
  SEC_EXTRA="$(section_gc_cflags)"
  UNWIND_EXTRA="$(dep_unwind_cflags)"
  HARD_EXTRA="$(hardening_cflags)"   # stack canary and fortify, see _audio_only.sh
  export CFLAGS="-O2 -fPIC -I$PREFIX/include $LTO_EXTRA $VIS_EXTRA $SEC_EXTRA $UNWIND_EXTRA $HARD_EXTRA"
  export CXXFLAGS="$CFLAGS"
  export CPPFLAGS="-I$PREFIX/include"
  export LDFLAGS="-L$PREFIX/lib $LTO_EXTRA"
}

check_toolchain() {
  local missing=() t
  for t in meson ninja cmake pkg-config python3 git curl; do
    command -v "$t" >/dev/null 2>&1 || missing+=("$t")
  done
  [[ -x "$NDK_BIN/$NDK_TRIPLE-gcc" ]] || missing+=("$NDK_TRIPLE-gcc in $NDK_BIN")
  [[ ${#missing[@]} -gt 0 ]] && die "Missing toolchain binaries: ${missing[*]}"
  ok "Toolchain OK ($("$NDK_BIN/$NDK_TRIPLE-gcc" --version | head -1))"
}

# =============================================================================
# The dependencies are the shared cross_build_* of _cross.sh, on the toolchain
# of setup_toolchain (only what the audio-only webOS libmpv links: libass is
# stripped and the audio client stubs are not built). FFmpeg and mpv take
# the webOS arguments here.
# =============================================================================

build_ffmpeg() {
  # shellcheck disable=SC2086
  cross_build_ffmpeg webos \
    $FFMPEG_CROSS_ARGS \
    --disable-libxcb \
    --disable-libxcb-shm \
    --disable-libxcb-xfixes \
    --disable-libxcb-shape \
    --extra-cflags="$(eh_frame_cflags) $HARD_EXTRA" \
    --extra-libs="-lm -lpthread -ldl"
}

build_mpv() {
  [[ -f "$PREFIX/lib/libmpv.so" ]] && return
  log "Building mpv $MPV_VERSION..."
  cross_mpv_source

  # As on Linux (see build_libmpv_linux.sh), with libgcc linked in: the
  # library needs glibc, ALSA and the system's libstdc++ (libplacebo).
  local ld_args
  ld_args="-static-libgcc $(hardening_ldflags) -Wl,--gc-sections,--exclude-libs=ALL,--no-undefined,--as-needed$(mpv_elf_size_ldflags none)$(mpv_soname_ldflags)"
  [[ "${VIS_HIDDEN:-1}" != "0" ]] && \
    ld_args="$ld_args,--version-script=${SCRIPT_DIR}/shared/mpv.ver"
  local extra_libs="-lssl -lcrypto -lxml2 -lbz2 -llzma"

  # shellcheck disable=SC2046
  cross_mpv_build webos --cross-file "$CROSS_MESON_FILE" \
    --prefix="$PREFIX" \
    --libdir=lib \
    --buildtype=release \
    --default-library=shared \
    $(mpv_common_args) \
    -Dalsa=enabled \
    -Dpulse=disabled \
    -Dpipewire=disabled \
    -Dc_args="$(eh_frame_cflags) $HARD_EXTRA" \
    "-Dc_link_args=$ld_args $extra_libs" \
    "-Dcpp_link_args=$ld_args $extra_libs"
}

# =============================================================================
# Finalize: stage the .so, strip it, check what it needs at runtime.
# =============================================================================

finalize() {
  local release_dir="$LIBMPV_SCRIPTS_ROOT/builds/release"
  mkdir -p "$release_dir"
  local src
  src="$(ls "$PREFIX"/lib/libmpv.so.* 2>/dev/null | sort -V | tail -1 || true)"
  [[ -n "$src" ]] || src="$PREFIX/lib/libmpv.so"
  [[ -f "$src" ]] || fail "libmpv.so not found in $PREFIX/lib"
  local out="$release_dir/libmpv_webos-${ARCH}.so"
  cp "$(readlink -f "$src")" "$out"

  log "Stripping symbols..."
  "$STRIP" --strip-unneeded "$out"
  assert_soname "$out" "$READELF"
  assert_no_relr "$out" "$READELF"
  assert_hardening "$out" "$READELF"
  assert_glibc_floor "$out" "$WEBOS_GLIBC_FLOOR" "$READELF"
  # Only glibc, ALSA and libstdc++ of the system: anything else would be
  # missing on the TV.
  local needed unexpected
  needed="$(LC_ALL=C "$READELF" -d "$out" | awk '/NEEDED/ {gsub(/[\[\]]/,"",$NF); print $NF}')"
  unexpected="$(grep -Ev '^(libc\.so\.6|libm\.so\.6|libdl\.so\.2|libpthread\.so\.0|librt\.so\.1|ld-linux\.so\.3|libasound\.so\.2|libstdc\+\+\.so\.6)$' <<< "$needed" || true)"
  [[ -z "$unexpected" ]] || fail "unexpected runtime dependencies of $out: $(tr '\n' ' ' <<< "$unexpected")"
  grep -qx 'libasound.so.2' <<< "$needed" || fail "$out does not link ALSA"
  ok "NEEDED: $(tr '\n' ' ' <<< "$needed")"

  write_build_record "webos-$ARCH" "$PREFIX"
  local licenses=(mpv ffmpeg openssl libplacebo libxml2 zlib bzip2 xz speexdsp)
  patch_on libsmb2 && licenses+=(libsmb2)
  gpl_build && licenses+=(rubberband)
  write_licenses "webos-$ARCH" "$BUILD_DIR/src" "${licenses[@]}"

  local total_syms
  total_syms="$("$READELF" -W --dyn-syms "$out" 2>/dev/null | awk '$5=="GLOBAL" && $4=="FUNC" && $7!="UND" {n++} END{print n+0}')"
  ok "Symbols: $total_syms exported functions"
  ok "Output: $out"
}

# ── Main ──────────────────────────────────────────────────────────────────────
main() {
  libass_stripped || die "the webOS build has no font stack: keep strip_libass and strip_mpv_dead on"
  gpl_build && die "the webOS build is LGPL only (no librubberband build here)"
  check_toolchain
  setup_sysroot
  setup_toolchain
  mkdir -p "$BUILD_DIR/src" "$BUILD_DIR/build"

  CFLAGS="$CFLAGS -Os" cross_build_zlib
  CFLAGS="-Os -fPIC -D_FILE_OFFSET_BITS=64 $HARD_EXTRA" cross_build_bzip2
  CFLAGS="$CFLAGS -Os" cross_build_xz
  cross_build_speexdsp
  cross_build_libplacebo
  build_openssl "$PREFIX" "$BUILD_DIR" "$OPENSSL_TARGET" "$OPENSSL_EXTRA"
  cross_build_libsmb2
  CFLAGS="$CFLAGS -Os" cross_build_libxml2
  build_ffmpeg
  build_mpv

  finalize
  cleanup_build "$BUILD_DIR"
  ok "webOS build complete: builds/release/libmpv_webos-${ARCH}.so"
}

main "$@"
