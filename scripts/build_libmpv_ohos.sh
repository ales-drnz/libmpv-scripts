# =============================================================================
# build_libmpv_ohos.sh
#
# Compiles mpv as libmpv.so for OpenHarmony and HarmonyOS (OHOS): arm64-v8a
# for the phones, tablets and TVs, x86_64 for the emulators.
#
# === OUTPUT ===
# builds/release/libmpv_ohos-<arch>.so
#
# === SYSTEM ===
# Run inside the mpv-build-ohos image (`ohos` stage of docker/Dockerfile).
# The toolchain is the public OpenHarmony SDK's own (scripts/ohos/
# ohos_sdk.sh fetches it at its pin into $OHOS_SDK_DIR): its clang 15 for
# the aarch64-linux-ohos and x86_64-linux-ohos targets, with compiler-rt,
# libunwind and libc++, against the musl sysroot of the native API. libc++
# and libunwind are linked in, so the library needs no libc++_shared.so in
# the HAP: only libc.so and libohaudio.so of the system. Small wrappers
# named like a musl cross toolchain (aarch64-linux-musl-clang, ...) pass
# clang the target and the sysroot, so every build system takes them as it
# takes gcc. The audio output is ao_ohaudio (patches/mpv/ohos), the only
# one.
#
# Usage (from project root):
#   ./scripts/build_libmpv_ohos.sh --arch=arm64-v8a
#   ./scripts/build_libmpv_ohos.sh --arch=x86_64
#
# Options (env vars):
#   ARCH=arm64-v8a|x86_64   (default: arm64-v8a; --arch=… overrides)
#   OHOS_SDK_DIR=<dir>      (default: builds/ohos-sdk; fetched when missing)
#   JOBS=N                  (default: nproc)
#   FORCE_DOWNLOAD=1, KEEP_BUILD=1, WIPE_ALL=1, ENABLE_LTO_DEPS=0,
#   VIS_HIDDEN=0, SECTION_GC=0: as in build_libmpv_linux.sh
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

source "$SCRIPT_DIR/shared/_helpers.sh"
source "$SCRIPT_DIR/shared/_versions.sh"
source "$SCRIPT_DIR/shared/_audio_only.sh"
source "$SCRIPT_DIR/shared/_cross.sh"
source "$SCRIPT_DIR/build_openssl.sh"

# ── Parse args ────────────────────────────────────────────────────────────────
ARCH="${ARCH:-arm64-v8a}"
for arg in "$@"; do
  case "$arg" in
    --arch=*)   ARCH="${arg#--arch=}" ;;
    --help|-h)  grep -E '^# ' "$0" | sed 's/^# //'; exit 0 ;;
    *) die "Unknown argument: $arg" ;;
  esac
done

# Per arch (named as OpenHarmony names its ABIs, like Android): clang's
# target, the triple of the wrappers and of autotools (a musl one, which
# every config.sub knows), and the names FFmpeg, meson and OpenSSL know the
# CPU by.
case "$ARCH" in
  arm64-v8a)
    CLANG_TARGET="aarch64-linux-ohos"
    TRIPLE="aarch64-linux-musl"
    MESON_CPU_FAMILY="aarch64"; MESON_CPU="aarch64"
    OPENSSL_TARGET="linux-aarch64"
    FFMPEG_ARCH_ARGS="--arch=aarch64"
    ;;
  x86_64)
    CLANG_TARGET="x86_64-linux-ohos"
    TRIPLE="x86_64-linux-musl"
    MESON_CPU_FAMILY="x86_64"; MESON_CPU="x86_64"
    OPENSSL_TARGET="linux-x86_64"
    FFMPEG_ARCH_ARGS="--arch=x86_64"
    ;;
  *) die "Unsupported --arch=$ARCH (must be arm64-v8a or x86_64)" ;;
esac

JOBS="${JOBS:-$(nproc 2>/dev/null || echo 4)}"
export PATH="$HOME/.local/bin:/usr/local/bin:$PATH"

BUILD_DIR="${BUILD_DIR:-$LIBMPV_SCRIPTS_ROOT/builds/work/OHOS/$ARCH}"
PREFIX="$BUILD_DIR/prefix"
TOOLS="$BUILD_DIR/bin"
OHOS_SDK_DIR="${OHOS_SDK_DIR:-$LIBMPV_SCRIPTS_ROOT/builds/ohos-sdk}"
mkdir -p "$BUILD_DIR" "$PREFIX/include" "$PREFIX/lib" "$TOOLS"

# ── Mirror all stdout + stderr to a timestamped log file ─────────────────────
start_build_log "ohos-${ARCH}" 'build_ohos-*_*.log' \
  "FFmpeg:        $FFMPEG_VERSION   mpv: $MPV_VERSION   target: ohos/$ARCH" \
  "Toolchain:     OpenHarmony SDK clang --target=$CLANG_TARGET"

# ── SDK ───────────────────────────────────────────────────────────────────────
setup_sdk() {
  bash "$SCRIPT_DIR/ohos/ohos_sdk.sh" "$OHOS_SDK_DIR" native
  LLVM="$OHOS_SDK_DIR/native/llvm"
  SYSROOT="$OHOS_SDK_DIR/native/sysroot"
  [[ -x "$LLVM/bin/clang" && -d "$SYSROOT/usr/lib/$CLANG_TARGET" ]] || \
    die "no OHOS clang or sysroot for $CLANG_TARGET in $OHOS_SDK_DIR"
  OHOS_API="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["apiVersion"])' \
    "$OHOS_SDK_DIR/native/oh-uni-package.json")"
  ok "OpenHarmony SDK API $OHOS_API ($("$LLVM/bin/clang" --version | head -1))"
}

# ── Toolchain: the SDK's clang behind wrappers named like a cross toolchain ───
setup_toolchain() {
  local tool
  for tool in clang clang++; do
    cat > "$TOOLS/$TRIPLE-$tool" <<EOF
#!/usr/bin/env bash
# Generated by build_libmpv_ohos.sh: $tool for OHOS $ARCH.
exec "$LLVM/bin/$tool" --target=$CLANG_TARGET --sysroot="$SYSROOT" -fuse-ld=lld -Wno-unused-command-line-argument "\$@"
EOF
    chmod +x "$TOOLS/$TRIPLE-$tool"
  done
  for tool in ar ranlib nm strip readelf objcopy; do
    ln -sf "$LLVM/bin/llvm-$tool" "$TOOLS/$TRIPLE-$tool"
  done
  ln -sf "$TRIPLE-clang" "$TOOLS/$TRIPLE-gcc"
  ln -sf "$TRIPLE-clang++" "$TOOLS/$TRIPLE-g++"
  export PATH="$TOOLS:$PATH"

  export CC="$TRIPLE-clang" CXX="$TRIPLE-clang++"
  export AR="$TRIPLE-ar" RANLIB="$TRIPLE-ranlib" NM="$TRIPLE-nm"
  export STRIP="$TRIPLE-strip" READELF="$TRIPLE-readelf" OBJCOPY="$TRIPLE-objcopy"

  # The prefix's .pc files only: the sysroot has none.
  export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig"
  export PKG_CONFIG_PATH="$PKG_CONFIG_LIBDIR"
  export PKG_CONFIG="$TOOLS/$TRIPLE-pkg-config"
  cat > "$PKG_CONFIG" <<EOF
#!/usr/bin/env bash
# Generated by build_libmpv_ohos.sh: the prefix's .pc files only.
export PKG_CONFIG_LIBDIR="$PKG_CONFIG_LIBDIR"
export PKG_CONFIG_PATH="$PKG_CONFIG_LIBDIR"
exec pkg-config "\$@"
EOF
  chmod +x "$PKG_CONFIG"

  CROSS_MESON_FILE="$BUILD_DIR/cross-ohos-$ARCH.meson"
  cat > "$CROSS_MESON_FILE" <<EOF
# Generated by build_libmpv_ohos.sh.
[binaries]
c = '$CC'
cpp = '$CXX'
ar = '$AR'
ranlib = '$RANLIB'
strip = '$STRIP'
nm = '$NM'
pkgconfig = '$PKG_CONFIG'
cmake = 'cmake'

[host_machine]
system = 'linux'
cpu_family = '$MESON_CPU_FAMILY'
cpu = '$MESON_CPU'
endian = 'little'

[properties]
needs_exe_wrapper = true
EOF

  CROSS_CMAKE_FILE="$BUILD_DIR/cross-ohos-$ARCH.cmake"
  cat > "$CROSS_CMAKE_FILE" <<EOF
# Generated by build_libmpv_ohos.sh.
set(CMAKE_SYSTEM_NAME      Linux)
set(CMAKE_SYSTEM_PROCESSOR $MESON_CPU)
set(CMAKE_C_COMPILER       $CC)
set(CMAKE_CXX_COMPILER     $CXX)
set(CMAKE_AR     $LLVM/bin/llvm-ar CACHE FILEPATH "Archiver")
set(CMAKE_RANLIB $LLVM/bin/llvm-ranlib CACHE FILEPATH "Ranlib")
set(CMAKE_FIND_ROOT_PATH              $PREFIX $SYSROOT)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
EOF

  export CROSS_AUTOTOOLS_HOST="--host=$TRIPLE"
  export CROSS_BUILD_DIR="$BUILD_DIR"
  export CROSS_PREFIX_DIR="$PREFIX"
  export CROSS_TRIPLE="$TRIPLE"
  FFMPEG_CROSS_ARGS="--enable-cross-compile --cross-prefix=$TRIPLE- --cc=$CC --cxx=$CXX --target-os=linux $FFMPEG_ARCH_ARGS --pkg-config=$PKG_CONFIG"

  LTO_EXTRA="$(lto_deps_cflags)"
  VIS_EXTRA="$(vis_deps_cflags)"
  SEC_EXTRA="$(section_gc_cflags)"
  UNWIND_EXTRA="$(dep_unwind_cflags)"
  HARD_EXTRA="$(hardening_cflags)"   # stack canary and fortify, see _audio_only.sh
  export CFLAGS="-O2 -fPIC -I$PREFIX/include $LTO_EXTRA $VIS_EXTRA $SEC_EXTRA $UNWIND_EXTRA $HARD_EXTRA"
  export CXXFLAGS="$CFLAGS"
  export CPPFLAGS="-I$PREFIX/include"
  export LDFLAGS="-L$PREFIX/lib $LTO_EXTRA"
}

check_toolchain() {
  local missing=() t
  for t in meson ninja cmake pkg-config python3 git curl unzip nasm; do
    command -v "$t" >/dev/null 2>&1 || missing+=("$t")
  done
  [[ ${#missing[@]} -gt 0 ]] && die "Missing toolchain binaries: ${missing[*]}"
  ok "Toolchain OK"
}

# =============================================================================
# The dependencies are the shared cross_build_* of _cross.sh, on the toolchain
# of setup_toolchain (as on Tizen: libass stripped, no audio client stubs).
# FFmpeg and mpv take the OHOS arguments here.
# =============================================================================

build_ffmpeg() {
  # shellcheck disable=SC2086
  cross_build_ffmpeg ohos \
    $FFMPEG_CROSS_ARGS \
    --disable-libxcb \
    --disable-libxcb-shm \
    --disable-libxcb-xfixes \
    --disable-libxcb-shape \
    --extra-cflags="$(eh_frame_cflags) $HARD_EXTRA" \
    --extra-libs="-lm -lpthread -ldl"
}

build_mpv() {
  [[ -f "$PREFIX/lib/libmpv.so" ]] && return
  log "Building mpv $MPV_VERSION..."
  cross_mpv_source
  python3 "$LIBMPV_SCRIPTS_ROOT/patches/mpv/ohos/patch_ao_ohaudio.py" "$CROSS_MPV_DIR"
  record_patch ao_ohaudio

  # As on Tizen, with the SDK's libc++, libc++abi and libunwind (libplacebo
  # is C++) linked in: the library needs only musl and OHAudio. Plain RELA:
  # the RELR of musl 1.2.4 is not promised by every OHOS loader.
  local ld_args
  ld_args="-static-libstdc++ -static-libgcc $(hardening_ldflags) -Wl,--gc-sections,--exclude-libs=ALL,--no-undefined,--as-needed$(mpv_elf_size_ldflags none)$(mpv_soname_ldflags)"
  [[ "${VIS_HIDDEN:-1}" != "0" ]] && \
    ld_args="$ld_args,--version-script=${SCRIPT_DIR}/shared/mpv.ver"
  # With the prefix's dir: meson's own checks (find_library of ohaudio)
  # link with these arguments too.
  local extra_libs="-L$PREFIX/lib -lssl -lcrypto -lxml2 -lbz2 -llzma"

  # shellcheck disable=SC2046
  cross_mpv_build ohos --cross-file "$CROSS_MESON_FILE" \
    --prefix="$PREFIX" \
    --libdir=lib \
    --buildtype=release \
    --default-library=shared \
    $(mpv_common_args) \
    -Dohaudio=enabled \
    -Dalsa=disabled \
    -Dpulse=disabled \
    -Dpipewire=disabled \
    -Dc_args="$(eh_frame_cflags) $HARD_EXTRA" \
    "-Dc_link_args=$ld_args $extra_libs" \
    "-Dcpp_link_args=$ld_args $extra_libs"
}

# =============================================================================
# Finalize: stage the .so, strip it, check what it needs at runtime.
# =============================================================================

finalize() {
  local release_dir="$LIBMPV_SCRIPTS_ROOT/builds/release"
  mkdir -p "$release_dir"
  local src
  src="$(ls "$PREFIX"/lib/libmpv.so.* 2>/dev/null | sort -V | tail -1 || true)"
  [[ -n "$src" ]] || src="$PREFIX/lib/libmpv.so"
  [[ -f "$src" ]] || fail "libmpv.so not found in $PREFIX/lib"
  local out="$release_dir/libmpv_ohos-${ARCH}.so"
  cp "$(readlink -f "$src")" "$out"

  log "Stripping symbols..."
  "$STRIP" --strip-unneeded "$out"
  assert_soname "$out" "$READELF"
  assert_no_relr "$out" "$READELF"
  assert_hardening "$out" "$READELF"
  # Only musl and OHAudio: anything else would be missing on the device.
  local needed unexpected
  needed="$(LC_ALL=C "$READELF" -d "$out" | awk '/NEEDED/ {gsub(/[\[\]]/,"",$NF); print $NF}')"
  unexpected="$(grep -Ev '^(libc\.so|libohaudio\.so|libhilog_ndk\.z\.so)$' <<< "$needed" || true)"
  [[ -z "$unexpected" ]] || fail "unexpected runtime dependencies of $out: $(tr '\n' ' ' <<< "$unexpected")"
  grep -qx 'libohaudio.so' <<< "$needed" || fail "$out does not link libohaudio"
  ok "NEEDED: $(tr '\n' ' ' <<< "$needed")"

  write_build_record "ohos-$ARCH" "$PREFIX"
  local licenses=(mpv ffmpeg openssl libplacebo libxml2 zlib bzip2 xz speexdsp)
  patch_on libsmb2 && licenses+=(libsmb2)
  write_licenses "ohos-$ARCH" "$BUILD_DIR/src" "${licenses[@]}"

  local total_syms
  total_syms="$("$READELF" -W --dyn-syms "$out" 2>/dev/null | awk '$5=="GLOBAL" && $4=="FUNC" && $7!="UND" {n++} END{print n+0}')"
  ok "Symbols: $total_syms exported functions"
  ok "Output: $out"
}

# ── Main ──────────────────────────────────────────────────────────────────────
main() {
  libass_stripped || die "the OHOS build has no font stack: keep strip_libass and strip_mpv_dead on"
  gpl_build && die "the OHOS build is LGPL only (no librubberband build here)"
  check_toolchain
  setup_sdk
  setup_toolchain
  mkdir -p "$BUILD_DIR/src" "$BUILD_DIR/build"

  CFLAGS="$CFLAGS -Os" cross_build_zlib
  CFLAGS="-Os -fPIC -D_FILE_OFFSET_BITS=64 $HARD_EXTRA" cross_build_bzip2
  CFLAGS="$CFLAGS -Os" cross_build_xz
  cross_build_speexdsp
  cross_build_libplacebo
  build_openssl "$PREFIX" "$BUILD_DIR" "$OPENSSL_TARGET" ""
  cross_build_libsmb2
  CFLAGS="$CFLAGS -Os" cross_build_libxml2
  build_ffmpeg
  build_mpv

  finalize
  cleanup_build "$BUILD_DIR"
  ok "OHOS build complete: builds/release/libmpv_ohos-${ARCH}.so"
}

main "$@"
